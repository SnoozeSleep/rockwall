/*
 * Brush-stroke flourishes under headings (client brief, November 2026: "orange brush-underline positioned relative to the
 * heading box, not hardcoded px"). The builder places its SVG decorations (the orange brush under "No More Guess Work!…"
 * on the home page and the like) as separate `c-svg` elements after the heading and pulls them up with a fixed negative
 * pixel margin (−5 … −12px), which assumes the heading's exact rendered height: with a fallback font or a different wrap
 * the stroke sat across the text. This script finds every such decoration that follows a text element (heading,
 * sub-heading, paragraph) in the generated pages (app/**／content.ts) and writes overrides into overrides/global.css:
 * the wrapper hangs off the bottom edge of the heading box (no negative margin) and the stroke is tucked up by a share
 * of ITS OWN height (a percentage transform), so the offset never depends on the text's metrics. Decorations that follow
 * an image (a stroke under a picture) are left as they are. Idempotent.  node scripts/svg-flourish.mjs [--check]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');
const CSS_FILE = path.join(ROOT, 'overrides', 'global.css');
const START = '/* ---- snz-svg-flourish:start';
const END = '/* ---- snz-svg-flourish:end ---- */';
const TUCK = '-30%'; // of the stroke's own height

const files = [];
(function walk(d) { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); if (e.isDirectory()) walk(p); else if (e.name === 'content.ts') files.push(p); } })(path.join(ROOT, 'app'));

const found = new Map(); // id -> { after, margin, pages }
for (const f of files) {
  const s = fs.readFileSync(f, 'utf8');
  for (const m of s.matchAll(/\.(svg-[A-Za-z0-9_-]+)\{text-align:[a-z]+;margin:(-\d+px)[^}]*\}/g)) {
    const [, id, margin] = m;
    const at = s.indexOf(`id=\\"${id}\\"`) >= 0 ? s.indexOf(`id=\\"${id}\\"`) : s.indexOf(`id="${id}"`);
    if (at < 0) continue; // a rule without an element
    const before = s.slice(Math.max(0, at - 5000), at);
    const prev = [...before.matchAll(/id=\\?"((?:sub-heading|heading|paragraph|image|bulletList|button|svg)-[A-Za-z0-9_-]+)\\?"/g)].map((x) => x[1]);
    const after = prev[prev.length - 1] || '';
    if (!found.has(id)) found.set(id, { after, margin, pages: new Set() });
    found.get(id).pages.add(path.relative(ROOT, f).replace(/\\/g, '/').replace(/\/content\.ts$/, '').replace(/^app\/\(en\)/, '').replace(/^app\/es/, '/es') || '/');
  }
}
const textOnes = [...found.entries()].filter(([, v]) => /^(sub-heading|heading|paragraph)-/.test(v.after)).sort(([a], [b]) => a.localeCompare(b));
const imageOnes = [...found.entries()].filter(([, v]) => !/^(sub-heading|heading|paragraph)-/.test(v.after));

const lines = [
  `${START} — generated by scripts/svg-flourish.mjs; do not edit by hand ----`,
  '   The builder pulls its brush-stroke decorations up under headings with fixed negative pixel margins, which assume the',
  '   heading\'s exact rendered height (with a fallback font the stroke sat across the text). Each one now hangs off the',
  '   bottom edge of the heading box, tucked up by a share of its own height — nothing depends on the text\'s metrics. ---- */',
];
for (const [id, v] of textOnes) {
  lines.push(`/* ${id}: after ${v.after} (builder margin-top ${v.margin}) on ${[...v.pages].slice(0, 4).join(', ')}${v.pages.size > 4 ? ` +${v.pages.size - 4}` : ''} */`);
  lines.push(`html .hl_page-preview--content .${id} { margin-top: 0 !important; line-height: 0; }`);
  lines.push(`html .hl_page-preview--content .${id} .svg-component { transform: translateY(${TUCK}); }`);
}
lines.push(END);
const block = lines.join('\n');

let css = fs.readFileSync(CSS_FILE, 'utf8');
const nl = css.includes('\r\n') ? '\r\n' : '\n';
const si = css.indexOf(START), ei = css.indexOf(END);
const next = si >= 0 && ei > si ? css.slice(0, si) + block.replace(/\n/g, nl) + css.slice(ei + END.length) : css.replace(/\s*$/, '') + nl + nl + block.replace(/\n/g, nl) + nl;
console.log(`${found.size} builder SVG decoration(s) with a negative top margin: ${textOnes.length} under text (re-anchored), ${imageOnes.length} under images (left alone: ${imageOnes.map(([id, v]) => `${id} after ${v.after}`).join('; ') || 'none'})`);
if (next === css) { console.log('overrides/global.css flourish block up to date'); process.exit(0); }
if (CHECK) { console.error('overrides/global.css flourish block is stale: run node scripts/svg-flourish.mjs'); process.exit(1); }
fs.writeFileSync(CSS_FILE, next);
console.log('overrides/global.css: flourish block written');
